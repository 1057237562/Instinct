const assert=require('node:assert/strict');
const {Tracker,duration,describe}=require('../src/transfer_rates.js');
const task={id:'upload',status:'uploading',upload_phase:'transferring',upload_mode:'sftp',upload_attempt:1,
  upload_total_bytes:1000,upload_done_bytes:800,upload_transferred_bytes:0};
const tracker=new Tracker();
assert.equal(tracker.observe(task,1000).rate,null,'first observation is a baseline');
let metrics=tracker.observe({...task,upload_done_bytes:900},4000);
assert.equal(metrics.rate,0,'resume/skip credits must not look like transferred bytes');
metrics=tracker.observe({...task,upload_done_bytes:950,upload_transferred_bytes:50},6000);
assert.equal(metrics.rate,10);assert.equal(metrics.eta,5);
assert.match(describe(task,metrics,n=>`${n} B`),/10 B\/s.*5 秒/);
assert.match(describe({...task,upload_mode:'pull'},metrics,String),/落盘估算速率/);
assert.equal(tracker.observe({...task,upload_attempt:2},7000).rate,null,'new attempt resets history');
tracker.observe({...task,upload_attempt:2,upload_transferred_bytes:100},10000);
for(const time of [13000,16000,19000,22000])metrics=tracker.observe({...task,upload_attempt:2,upload_transferred_bytes:100},time);
assert.equal(metrics.rate,0,'stalled uploads must lose their old rate');
assert.equal(metrics.eta,null);
assert.equal(tracker.observe({...task,upload_attempt:2,upload_transferred_bytes:150},60000).rate,null,'long tab pause resets history');
assert.equal(tracker.observe({...task,upload_attempt:2,upload_transferred_bytes:0},63000).rate,null,'counter rollback resets history');
metrics=tracker.observe({...task,upload_phase:'verifying'},65000);
assert.equal(metrics.rate,null);assert.match(describe(task,metrics,String),/校验/);assert.equal(tracker.samples.size,0);
assert.match(describe(task,{stale:true},String),/等待重新连接/);
assert.equal(describe({...task,status:'failed'},metrics,String),'');
const legacy={id:'old',status:'uploading',upload_mode:'sftp',upload_done_bytes:300,upload_total_bytes:1000};
assert.equal(tracker.observe(legacy,1000).rate,null);
assert.equal(tracker.observe({...legacy,upload_done_bytes:600},4000).rate,100);
assert.equal(tracker.observe({...legacy,upload_done_bytes:1000},7000).phase,'verifying');
tracker.retain(new Set());assert.equal(tracker.samples.size,0);
assert.equal(duration(null),'—');assert.equal(duration(61),'1 分 1 秒');assert.equal(duration(7199),'2 小时 0 分');
console.log('PASS: resumed credits, rolling speed, ETA, stalls, retry/reset, phase changes, legacy API and formatting.');
