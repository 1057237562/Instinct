def apply_rules(text, rules, log):
    """Apply (pattern, repl) rules; return new text and record (old, new) matches."""
    for pat, repl in rules:
        new_text, n = re.subn(pat, repl, text)
        if n:
            for m in re.finditer(pat, text):
                log.append([m.group(0), repl])
            text = new_text
    return text

def make_edits(field_old, field_new):
    """Character-level diff -> span-aware, unique (old, new) hunks."""
    sm = difflib.SequenceMatcher(None, field_old, field_new, autojunk=False)
    hunks = []
    for tag, i1, i2, j1, j2 in sm.get_opcodes():
        if tag == 'equal':
            continue
        if hunks and i1 - hunks[-1][1] <= 8:
            hunks[-1][1] = i2
            hunks[-1][3] = j2
        else:
            hunks.append([i1, i2, j1, j2])
    out = []
    for k, (i1, i2, j1, j2) in enumerate(hunks):
        lo_limit = hunks[k - 1][1] if k > 0 else 0
        hi_limit = hunks[k + 1][0] if k + 1 < len(hunks) else len(field_old)
        left, right = i1, i2
        while True:
            if field_old.count(field_old[left:right]) == 1:
                break
            moved = False
            if right < hi_limit:
                right += 1
                moved = True
            elif left > lo_limit:
                left -= 1
                moved = True
            if not moved:
                break
        old = field_old[left:right]
        new = field_new[j1 - (i1 - left):j2 + (right - i2)]
        out.append([old, new])
    return out

